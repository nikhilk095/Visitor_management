CREATE TABLE IF NOT EXISTS login (
    login_id VARCHAR(20) PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS visitors (
    visitor_id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    id_proof VARCHAR(50),
    department VARCHAR(80)
);

CREATE TABLE IF NOT EXISTS visits (
    visit_id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    visitor_id INTEGER NOT NULL,
    purpose VARCHAR(150),
    person_to_meet VARCHAR(100),
    check_in TIMESTAMP NOT NULL,
    check_out TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'Inside',
    CONSTRAINT fk_visits_visitor
        FOREIGN KEY (visitor_id)
        REFERENCES visitors(visitor_id)
);

